#!/usr/bin/env python3
"""
Builds firmware/sparky_hw_test/voice_sample.h for the hardware test's "v" test: Sparky's
Studio voice lines (16 kHz, exactly as the ESP32 stores them) plus one typical tutor answer
at the voice's own rate (22.05 kHz, as real answers arrive from /api/v1/voice/query).

The header is generated (gitignored) because it holds your own Studio lines. Re-run after
changing voice lines, then rebuild and upload the test:
    python scripts/make_hw_test_voice.py
"""
import io
import sys
import wave
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
OUT = ROOT / "firmware" / "sparky_hw_test" / "voice_sample.h"

ANSWER = ("Great question! Plants make their own food from sunlight, water and air. "
          "That is called photosynthesis. Which plant do you think grows the fastest?")


def samples(wav_bytes):
    with wave.open(io.BytesIO(wav_bytes)) as w:
        assert w.getnchannels() == 1 and w.getsampwidth() == 2
        rate = w.getframerate()
        frames = w.readframes(w.getnframes())
    return rate, [int.from_bytes(frames[i:i + 2], "little", signed=True) for i in range(0, len(frames), 2)]


def main():
    from core.services import studio_service as studio
    from core.services.voice_service import VoiceService

    clips = [(v["text"], (studio.VOICE_DIR / f"{v['id']}.wav").read_bytes())
             for v in studio.load()["voice_lines"] if (studio.VOICE_DIR / f"{v['id']}.wav").exists()]
    clips.append((ANSWER, VoiceService().synthesize(ANSWER)))

    out = ["// Generated by scripts/make_hw_test_voice.py - do not edit, do not commit.",
           "#pragma once", "#include <Arduino.h>",
           "struct VoiceClip { const char* text; uint32_t rate; uint32_t samples; const int16_t* data; };"]
    entries = []
    for i, (text, wav) in enumerate(clips):
        rate, pcm = samples(wav)
        out.append(f"static const int16_t CLIP{i}[] = {{")
        out += ["  " + ",".join(map(str, pcm[j:j + 24])) + "," for j in range(0, len(pcm), 24)]
        out.append("};")
        safe = text.replace("\\", "\\\\").replace('"', '\\"')
        entries.append(f'  {{"{safe}", {rate}, {len(pcm)}, CLIP{i}}},')
        print(f"{rate} Hz  {len(pcm) / rate:4.1f} s  {text}")
    out += ["static const VoiceClip VOICE_CLIPS[] = {", *entries, "};",
            f"static const int VOICE_CLIP_COUNT = {len(entries)};", ""]
    OUT.write_text("\n".join(out), encoding="utf-8")
    print(f"Wrote {OUT} ({OUT.stat().st_size // 1024} KB of source)")


if __name__ == "__main__":
    main()
